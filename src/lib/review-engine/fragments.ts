/**
 * Zero-cost review generation fragment libraries.
 *
 * No external AI API is used anywhere. Reviews are composed locally from these
 * fragments plus per-business data (name, city, services, service vocabulary).
 *
 * Placeholders:
 *   {business}  business name
 *   {services}  natural list of selected service names (lowercased)
 *   {service}   primary selected service
 *   {city}      business city
 *   {vocab}     a vocabulary word attached to the primary service
 */

export type Lang = "english" | "hinglish" | "hindi";
export type Sentiment = "excellent" | "good" | "average" | "not_good";

export type AttributeKey =
  | "quality"
  | "staff"
  | "finishing"
  | "pricing"
  | "speed"
  | "installation"
  | "product_range"
  | "communication"
  | "cleanliness"
  | "overall";

export const ATTRIBUTE_KEY_BY_LABEL: Record<string, AttributeKey> = {
  "quality of work": "quality",
  staff: "staff",
  finishing: "finishing",
  pricing: "pricing",
  speed: "speed",
  installation: "installation",
  "product range": "product_range",
  communication: "communication",
  cleanliness: "cleanliness",
  "overall experience": "overall",
};

export function attributeKeyFor(label: string): AttributeKey {
  return ATTRIBUTE_KEY_BY_LABEL[label.trim().toLowerCase()] ?? "overall";
}

type AttributeBank = Record<AttributeKey, string[]>;

export interface LanguageLibrary {
  openings: string[];
  serviceContext: string[];
  experience: Record<Sentiment, string[]>;
  attributes: Record<"positive" | "neutral" | "negative", AttributeBank>;
  noteLeadIns: string[];
  closings: Record<"positive" | "neutral" | "negative", string[]>;
}

